<?php

namespace App\Models;

use App\Traits\HasCode;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Spatie\Activitylog\Models\Concerns\LogsActivity;
use Spatie\Activitylog\Support\LogOptions;

class Department extends Model
{
    use HasCode, HasFactory, LogsActivity;

    /**
     * Department whose members get read-only global visibility: they see every
     * record, but the policies deny every write.
     */
    public const MANAGEMENT = 'Management';

    /**
     * Departments whose members can be picked as the salesperson on an order.
     *
     * Matched on `name`, never on `code`: `code` is generated by HasCode
     * (MMG-DEP-000003), so it carries no meaning to filter on.
     */
    public const SALES = 'Sales';

    public const MARKETING = 'Marketing';

    public function getActivitylogOptions(): LogOptions
    {
        return LogOptions::defaults()
            ->logOnlyDirty()
            ->dontLogIfAttributesChangedOnly(['updated_at']);
    }

    protected $fillable = [
        'name',
        'code',
        'description',
    ];

    protected $codeColumn = 'code';

    protected $codePrefix = 'DEP';

    public function positions(): HasMany
    {
        return $this->hasMany(Position::class);
    }

    public function users(): HasMany
    {
        return $this->hasMany(User::class);
    }
}
